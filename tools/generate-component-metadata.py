"""Compile documentation metadata for the offline Flutter catalog (no runtime I/O)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def dart(value):
    if isinstance(value, str):
        return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"
    if isinstance(value, list):
        return '[' + ', '.join(dart(v) for v in value) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join(dart(k) + ': ' + dart(v) for k, v in value.items()) + '}'
    raise TypeError(type(value))


def build():
    registry = json.loads((ROOT / 'docs/design/components/registry.json').read_text(encoding='utf-8'))
    components = registry['components']
    names = {c['id']: c['name'] for c in components}
    states = {c['id']: c['applicableStates'] for c in components}
    fields = ['sourceScreenIds', 'anatomy', 'parameters', 'events', 'variants', 'limitations', 'acceptanceCriteria', 'usageExample', 'runnableExamplePath', 'notApplicableReasons']
    cards = {c['id']: {field: c[field] for field in fields} for c in components}
    source = '// Generated by tools/generate-component-metadata.py from registry.json.\n'
    source += 'const componentNames = <String, String>' + dart(names) + ';\n'
    source += 'const componentStates = <String, List<String>>' + dart(states) + ';\n'
    source += 'const componentDocumentation = <String, Map<String, Object>>' + dart(cards) + ';\n'
    (ROOT / 'tool/component_catalog/names.dart').write_text(source, encoding='utf-8')


if __name__ == '__main__':
    build()
