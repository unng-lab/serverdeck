      'flutter test $verificationTest --plain-name "$screenId"';
  String get result => 'not-run';
  DesignStateOrigin get stateApplicability =>
      designStateOrigins.singleWhere((origin) => origin.originId == screenId);
  String get scope =>
      'Production widget/section with synthetic existing-protocol input; future adoption/layout/state evidence. Registry checks and construction do not prove visual acceptance or native controller/auth/effects.';
